      <h2>1. Introducción</h2>
      <p>En Valores Casa de Bolsa S.A. (en adelante, la “Sociedad”) valoramos la privacidad de nuestros clientes, potenciales clientes, usuarios y demás personas que interactúan con nosotros.</p>
      <p>La presente Política de Privacidad tiene por objeto informar cómo recopilamos, utilizamos, almacenamos y protegemos los datos personales, de conformidad con la legislación paraguaya vigente y demás normativa aplicable.</p>

      <h2>2. Datos personales que recopilamos</h2>
      <p>La Sociedad podrá recopilar y tratar los datos personales que sean necesarios para la prestación de sus servicios, incluyendo, entre otros:</p>
      <ul>
        <li>Datos de identificación y contacto.</li>
        <li>Información requerida para la apertura y administración de cuentas.</li>
        <li>Información relacionada con las operaciones e instrucciones impartidas por los clientes.</li>
        <li>Información obtenida mediante el uso del sitio web o de las plataformas habilitadas por la Sociedad, cuando corresponda.</li>
      </ul>

      <h2>3. Finalidad del tratamiento</h2>
      <p>Los datos personales serán tratados para las siguientes finalidades:</p>
      <ul>
        <li>Prestar los servicios ofrecidos por la Sociedad.</li>
        <li>Gestionar la relación comercial con los clientes.</li>
        <li>Cumplir obligaciones legales, regulatorias y contractuales.</li>
        <li>Prevenir fraudes y gestionar riesgos.</li>
        <li>Atender consultas, solicitudes y reclamos.</li>
        <li>Mejorar nuestros servicios y canales de atención.</li>
      </ul>

      <h2>4. Confidencialidad</h2>
      <p>La Sociedad tratará los datos personales con estricta confidencialidad y únicamente los utilizará para las finalidades previstas en esta Política y en la normativa vigente.</p>
      <p>La información podrá ser comunicada a autoridades competentes cuando exista una obligación legal o regulatoria, o a terceros cuando ello resulte necesario para la prestación de los servicios contratados o medie autorización del titular de los datos, según corresponda.</p>

      <h2>5. Seguridad de la información</h2>
      <p>La Sociedad adopta medidas administrativas, organizativas y técnicas razonables para proteger los datos personales contra el acceso, uso, modificación, divulgación o destrucción no autorizados.</p>
      <p>Estas medidas podrán ser actualizadas conforme evolucionen los riesgos y las mejores prácticas en materia de seguridad de la información.</p>

      <h2>6. Conservación de los datos</h2>
      <p>Los datos personales serán conservados durante el tiempo necesario para cumplir las finalidades para las cuales fueron recopilados y por los plazos establecidos en la legislación y normativa aplicables.</p>

      <h2>7. Derechos de los titulares</h2>
      <p>Los titulares de los datos personales podrán ejercer los derechos que les reconoce la legislación paraguaya vigente en materia de protección de datos personales, a través de los canales de contacto habilitados por la Sociedad.</p>

      <h2>8. Modificaciones</h2>
      <p>La Sociedad podrá modificar la presente Política de Privacidad para adecuarla a cambios legales, regulatorios o a mejoras en sus procesos internos. La versión vigente estará disponible en el sitio web institucional.</p>

      <h2>9. Contacto</h2>
      <p>Para consultas relacionadas con esta Política de Privacidad o con el tratamiento de datos personales, podrá comunicarse con la Sociedad a través de los canales oficiales publicados en su sitio web.</p>
