    <div class="grid lg:grid-cols-2 gap-10">
      <div class="animate-fade-up">
        <div class="section-tag">Contexto</div>
        <h2 class="section-title mt-2">Una evolución del sistema existente</h2>
        <p class="text-gray-txt leading-relaxed mt-4">Antes del Investor Pass, ya existía en Paraguay un proceso especial para inversores a través del <strong>Sistema SUACE</strong>, que exige una inversión mínima de USD 70.000 en un emprendimiento empresarial y el compromiso de generar al menos cinco puestos de trabajo formales.</p>
        <p class="text-gray-txt leading-relaxed mt-3">Ese esquema continúa plenamente vigente y sigue siendo una opción válida para quienes deseen radicarse a través de una inversión vinculada a la creación de empleo.</p>
        <p class="text-gray-txt leading-relaxed mt-3">El Investor Pass se suma como una <strong>nueva vía</strong>, que permite acceder a la residencia permanente a través de modalidades de inversión que no requieren obligatoriamente la conformación de una empresa ni la generación de puestos de trabajo.</p>
      </div>
      <div class="animate-fade-up animate-delay-2">
        <div class="section-tag">Ventajas</div>
