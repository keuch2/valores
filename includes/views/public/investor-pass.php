        <div class="space-y-3 mt-4">
          <div class="card p-5 flex items-center gap-4"><div class="text-2xl text-gray-txt"><i class="fa-regular fa-clock"></i></div><div><div class="font-bold text-blue-inst">Residente temporal</div><p class="text-sm text-gray-txt">No puede ausentarse de Paraguay por más de <strong>un año</strong> de forma injustificada sin riesgo de perder su estatus.</p></div></div>
